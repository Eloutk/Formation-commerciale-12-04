CREATE TABLE IF NOT EXISTS public.link_day_facts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
  day SMALLINT NOT NULL CHECK (day BETWEEN 1 AND 31),
  title TEXT NOT NULL,
  context TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT link_day_facts_month_day_uidx UNIQUE (month, day)
);

CREATE INDEX IF NOT EXISTS link_day_facts_month_day_idx
  ON public.link_day_facts (month, day);

ALTER TABLE public.link_day_facts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated read link_day_facts" ON public.link_day_facts;
CREATE POLICY "Authenticated read link_day_facts"
  ON public.link_day_facts FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Admins manage link_day_facts" ON public.link_day_facts;
CREATE POLICY "Admins manage link_day_facts"
  ON public.link_day_facts FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND p.role IN ('admin', 'super_admin')
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = auth.uid() AND p.role IN ('admin', 'super_admin')
    )
  );

CREATE OR REPLACE FUNCTION public.get_todays_link_day_facts()
RETURNS TABLE (id BIGINT, title TEXT, context TEXT)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT f.id, f.title, f.context
  FROM public.link_day_facts f
  WHERE f.month = EXTRACT(MONTH FROM (NOW() AT TIME ZONE 'Europe/Paris'))::int
    AND f.day = EXTRACT(DAY FROM (NOW() AT TIME ZONE 'Europe/Paris'))::int
  ORDER BY f.id;
$$;

GRANT EXECUTE ON FUNCTION public.get_todays_link_day_facts() TO authenticated;

